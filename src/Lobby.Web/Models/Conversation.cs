namespace Lobby.Web.Models;

public enum ConversationType { Direct, Group }

public class Conversation
{
    public const int NameMaxLength = 60;
    public const int MaxGroupMembers = 20;

    public int Id { get; set; }
    public ConversationType Type { get; set; }
    public string? Name { get; set; } // groups only
    public string CreatedById { get; set; } = "";
    public ApplicationUser CreatedBy { get; set; } = null!;
    public DateTimeOffset CreatedAt { get; set; }

    // "{smallerUserId}|{largerUserId}" for direct chats, null for groups.
    // A unique index on it makes "one DM per pair" a database rule, not just a code rule.
    public string? DirectKey { get; set; }

    public DateTimeOffset? LastMessageAt { get; set; }

    public List<ConversationMember> Members { get; set; } = [];
    public List<Message> Messages { get; set; } = [];

    // Ordinal comparison: the same two ids must give the same key on every machine and culture.
    public static string MakeDirectKey(string userA, string userB) =>
        string.CompareOrdinal(userA, userB) < 0 ? $"{userA}|{userB}" : $"{userB}|{userA}";
}

// The join table of the many-to-many between users and conversations, with a payload
// (JoinedAt, LastReadAt), which is why it is an entity of its own.
public class ConversationMember
{
    public int ConversationId { get; set; }
    public Conversation Conversation { get; set; } = null!;
    public string UserId { get; set; } = "";
    public ApplicationUser User { get; set; } = null!;
    public DateTimeOffset JoinedAt { get; set; }

    // Only used for MY unread badge. Never shown to other people (no read receipts).
    public DateTimeOffset? LastReadAt { get; set; }
}

public class Message
{
    public const int MaxBodyLength = 2000;

    public int Id { get; set; } // identity: also the order of messages and the paging key
    public int ConversationId { get; set; }
    public Conversation Conversation { get; set; } = null!;
    public string SenderId { get; set; } = "";
    public ApplicationUser Sender { get; set; } = null!;
    public string Body { get; set; } = "";
    public DateTimeOffset SentAt { get; set; } // server time, never the client's clock

    // Generated by the browser. Unique per sender, so a resend after a dropped connection is not saved twice.
    public Guid ClientMessageId { get; set; }
}
